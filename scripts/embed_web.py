# PlatformIO pre-build script: gzip web/index.html into src/web_page_gen.c.
#
# Runs on every `pio run`, so editing web/index.html and rebuilding always
# puts the new page into the firmware. If the page is missing or empty a small
# built-in placeholder is embedded instead, so the build never fails because of
# the web UI. The output file is only rewritten when its content changes.

import gzip
import os

try:
    Import("env")  # noqa: F821  (provided by PlatformIO/SCons)
    PROJECT_DIR = env.subst("$PROJECT_DIR")  # noqa: F821
except NameError:  # allow running by hand: python scripts/embed_web.py
    PROJECT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

SRC_PAGE = os.path.join(PROJECT_DIR, "web", "index.html")
OUT_FILE = os.path.join(PROJECT_DIR, "src", "web_page_gen.c")

PLACEHOLDER = b"""<!doctype html>
<html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>ESPKB</title></head>
<body style="font-family:sans-serif;max-width:40em;margin:2em auto;padding:0 1em">
<h1>ESPKB</h1>
<p>The web UI was not included in this firmware build.</p>
<p>The HTTP API is available: <a href="/api">/api</a> describes all endpoints,
<a href="/api/status">/api/status</a> shows the device state.</p>
</body></html>
"""


def main():
    page = b""
    if os.path.isfile(SRC_PAGE):
        with open(SRC_PAGE, "rb") as f:
            page = f.read()
    placeholder = len(page.strip()) == 0
    if placeholder:
        page = PLACEHOLDER

    gz = gzip.compress(page, compresslevel=9, mtime=0)

    lines = [
        "/* Generated by scripts/embed_web.py from web/index.html - do not edit. */",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "/* source: %s, %d bytes raw, %d bytes gzip */"
        % ("built-in placeholder" if placeholder else "web/index.html", len(page), len(gz)),
        "const int web_page_is_placeholder = %d;" % (1 if placeholder else 0),
        "const size_t web_page_gz_len = %d;" % len(gz),
        "const uint8_t web_page_gz[] = {",
    ]
    for i in range(0, len(gz), 16):
        lines.append("    " + ", ".join("0x%02x" % b for b in gz[i:i + 16]) + ",")
    lines.append("};")
    content = "\n".join(lines) + "\n"

    old = None
    if os.path.isfile(OUT_FILE):
        with open(OUT_FILE, "r") as f:
            old = f.read()
    if old != content:
        with open(OUT_FILE, "w") as f:
            f.write(content)
        print("embed_web: wrote %s (%s, %d bytes gzip)"
              % (os.path.relpath(OUT_FILE, PROJECT_DIR),
                 "placeholder" if placeholder else "web/index.html", len(gz)))


main()
